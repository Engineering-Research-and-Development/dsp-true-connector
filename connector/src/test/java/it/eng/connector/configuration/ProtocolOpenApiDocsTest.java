package it.eng.connector.configuration;

import static org.junit.jupiter.api.Assertions.assertTrue;

import it.eng.catalog.rest.protocol.CatalogController;
import it.eng.datatransfer.rest.protocol.ConsumerDataTransferCallbackController;
import it.eng.datatransfer.rest.protocol.ProviderDataTransferController;
import it.eng.negotiation.rest.protocol.ContractNegotiationConsumerCallbackController;
import it.eng.negotiation.rest.protocol.ContractNegotiationProviderController;
import java.lang.reflect.Method;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.annotation.AnnotatedElementUtils;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;

class ProtocolOpenApiDocsTest {

    private static final List<Class<?>> PROTOCOL_CONTROLLERS = List.of(
            CatalogController.class,
            ContractNegotiationProviderController.class,
            ContractNegotiationConsumerCallbackController.class,
            ProviderDataTransferController.class,
            ConsumerDataTransferCallbackController.class);
    private static final Set<String> PROTOCOL_EXAMPLES = Set.of(
            "catalog-request.protocol",
            "contract-request-initial.protocol",
            "contract-request-counteroffer.protocol",
            "contract-offer-initial.protocol",
            "contract-offer-counteroffer.protocol",
            "contract-agreement.protocol",
            "contract-agreement-verification.protocol",
            "contract-negotiation-event-accepted.protocol",
            "contract-negotiation-event-finalized.protocol",
            "contract-negotiation-termination.protocol",
            "transfer-request.protocol",
            "transfer-start.protocol",
            "transfer-completion.protocol",
            "transfer-suspension.protocol",
            "transfer-termination.protocol");

    @Test
    @DisplayName("Documents every standard DSP controller operation and its error shape")
    void documentsStandardProtocolOperations() {
        OpenApiDocs documentation = docsLoader().load();
        List<String> undocumentedOperations = protocolOperations().stream()
                .map(operation -> missingDocumentation(operation.controller(), operation.method(), documentation))
                .filter(message -> !message.isEmpty())
                .toList();

        assertTrue(undocumentedOperations.isEmpty(),
                () -> "DSP operations are missing authorization, error, or summary documentation: "
                        + String.join("; ", undocumentedOperations));
    }

    @Test
    @DisplayName("Loads all protocol JSON-LD examples generated by module fixtures")
    void loadsAllProtocolExamples() {
        OpenApiDocs documentation = docsLoader().load();

        assertTrue(documentation.examples().keySet().containsAll(PROTOCOL_EXAMPLES),
                () -> "Missing generated DSP examples: " + PROTOCOL_EXAMPLES.stream()
                        .filter(example -> !documentation.examples().containsKey(example))
                        .toList());
    }

    private static OpenApiDocsLoader docsLoader() {
        return new OpenApiDocsLoader(new PathMatchingResourcePatternResolver());
    }

    private static List<ControllerOperation> protocolOperations() {
        return PROTOCOL_CONTROLLERS.stream()
                .flatMap(controller -> Arrays.stream(controller.getDeclaredMethods())
                        .filter(ProtocolOpenApiDocsTest::isStandardProtocolOperation)
                        .map(method -> new ControllerOperation(controller, method)))
                .toList();
    }

    private static boolean isStandardProtocolOperation(final Method method) {
        RequestMapping mapping = AnnotatedElementUtils.findMergedAnnotation(method, RequestMapping.class);
        return mapping != null && Arrays.stream(mapping.path())
                .noneMatch(path -> path.equals("/tck") || path.endsWith("/tck"));
    }

    private static String missingDocumentation(
            final Class<?> controller,
            final Method method,
            final OpenApiDocs documentation) {
        String operationKey = controller.getSimpleName() + "." + method.getName();
        OpenApiOperationDocs operation = documentation.operations().get(operationKey);
        if (operation == null || !controller.getSimpleName().equals(operation.properties().get("controllerName"))
                || !method.getName().equals(operation.methodName())
                || operation.methodParameters()
                        .map(expected -> !expected.equals(Arrays.stream(method.getParameterTypes())
                                .map(Class::getTypeName)
                                .toList()))
                        .orElse(false)) {
            return operationKey + " has no matching controller-scoped OpenAPI entry";
        }
        Object summary = operation.properties().get("summary");
        Object description = operation.properties().get("description");
        if (!(summary instanceof String summaryText) || summaryText.isBlank()
                || !(description instanceof String descriptionText) || descriptionText.isBlank()
                || !descriptionText.contains("ROLE_CONNECTOR")) {
            return operationKey + " is missing its summary or ROLE_CONNECTOR authorization note";
        }

        Object responsesValue = operation.properties().get("responses");
        if (!(responsesValue instanceof Map<?, ?> responses)
                || !(responses.get("400") instanceof Map<?, ?> badRequest)
                || !(badRequest.get("description") instanceof String errorDescription)
                || !errorDescription.contains(errorModelName(controller))) {
            return operationKey + " is missing the 400 error response shape from its exception advice";
        }

        boolean hasRequestBody = Arrays.stream(method.getParameters())
                .anyMatch(parameter -> parameter.isAnnotationPresent(RequestBody.class));
        if (hasRequestBody && requestExampleNames(operation.properties().get("requestExamples")).stream()
                .noneMatch(name -> documentation.examples().containsKey(name + ".protocol"))) {
            return operationKey + " is missing a generated protocol request example";
        }
        return "";
    }

    private static String errorModelName(final Class<?> controller) {
        if (controller == CatalogController.class) {
            return "CatalogError";
        }
        if (controller == ContractNegotiationProviderController.class
                || controller == ContractNegotiationConsumerCallbackController.class) {
            return "ContractNegotiationErrorMessage";
        }
        return "TransferError";
    }

    private static List<String> requestExampleNames(final Object value) {
        if (value instanceof String exampleName) {
            return List.of(exampleName);
        }
        if (value instanceof List<?> exampleNames) {
            return exampleNames.stream()
                    .filter(String.class::isInstance)
                    .map(String.class::cast)
                    .toList();
        }
        if (value instanceof Map<?, ?> exampleNames) {
            return exampleNames.values().stream()
                    .filter(String.class::isInstance)
                    .map(String.class::cast)
                    .toList();
        }
        return List.of();
    }

    private record ControllerOperation(Class<?> controller, Method method) {
    }
}
